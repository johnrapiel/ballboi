#!/usr/bin/env node
// Generates artifacts/mobile/constants/tokens.ts from the Ball Boi design
// system snapshot in docs/design-system/tokens.json.
//
// Usage: node scripts/sync-design-tokens.mjs
// Refresh docs/design-system/tokens.json from the live design system first:
// https://claude.ai/artifact/XRuxb1uAfy18AQ1irQCkrf

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = resolve(root, "docs/design-system/tokens.json");
const out = resolve(root, "artifacts/mobile/constants/tokens.ts");

const tokens = JSON.parse(readFileSync(src, "utf8"));
const themes = tokens.color.themes.map((t) => t.id); // ["light", "dark"]
const first = themes[0];

// Resolve every color token to a concrete value per theme, following
// "{alias}" references and falling back to the first theme's value.
const byName = new Map(tokens.color.tokens.map((t) => [t.name, t]));
function resolveColor(name, theme, seen = new Set()) {
  if (seen.has(name)) throw new Error(`Circular color alias: ${name}`);
  seen.add(name);
  const token = byName.get(name);
  if (!token) throw new Error(`Unknown color token: ${name}`);
  const v = token.value;
  const raw = typeof v === "string" ? v : v[theme] ?? v[first];
  const alias = /^\{(.+)\}$/.exec(raw);
  return alias ? resolveColor(alias[1], theme, seen) : raw;
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const color = {};
for (const theme of themes) {
  color[theme] = {};
  for (const t of tokens.color.tokens) color[theme][camel(t.name)] = resolveColor(t.name, theme);
}

const px = (v) => (typeof v === "number" ? v : Number.parseFloat(v));
const spacing = Object.fromEntries(tokens.spacing.tokens.map((t) => [camel(t.name), px(t.value)]));
const radius = Object.fromEntries(tokens.radius.tokens.map((t) => [camel(t.name), px(t.value)]));

// Map each text style to the loaded font face for its family, weight, and style.
const FACES = {
  display: {
    "500": "CormorantGaramond_500Medium",
    "600": "CormorantGaramond_600SemiBold",
    "500italic": "CormorantGaramond_500Medium_Italic",
  },
  sans: {
    "400": "DMSans_400Regular",
    "500": "DMSans_500Medium",
    "600": "DMSans_600SemiBold",
    "700": "DMSans_700Bold",
  },
};
const type = {};
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    const key = `${s.fontWeight}${s.fontStyle === "italic" ? "italic" : ""}`;
    const fontFamily = FACES[group.family]?.[key];
    if (!fontFamily) throw new Error(`No font face for ${group.family} ${key} (${s.name})`);
    const size = px(s.fontSize);
    const style = { fontFamily, fontSize: size, lineHeight: px(s.lineHeight) };
    if (s.letterSpacing) style.letterSpacing = Number((Number.parseFloat(s.letterSpacing) * size).toFixed(2)); // em to points
    if (s.name === "label") style.textTransform = "uppercase";
    if (s.name === "score") style.fontVariant = ["lining-nums", "tabular-nums"];
    type[camel(s.name)] = style;
  }
}

const header = `// Generated by scripts/sync-design-tokens.mjs from docs/design-system/tokens.json.
// Don't edit by hand: update the design system, then run
//   node scripts/sync-design-tokens.mjs

import type { TextStyle } from "react-native";
`;
const body = `
export const color = ${JSON.stringify(color, null, 2)} as const;

export type ColorScheme = keyof typeof color;
export type ColorTokens = (typeof color)[ColorScheme];

export const spacing = ${JSON.stringify(spacing, null, 2)} as const;

export const radius = ${JSON.stringify(radius, null, 2)} as const;

export const type = ${JSON.stringify(type, null, 2)} satisfies Record<string, TextStyle>;

/** Minimum touch target, in points (Apple HIG, WCAG 2.5.8). */
export const MIN_TAP = 44;
`;
writeFileSync(out, header + body);
console.log(`Wrote ${out}`);
