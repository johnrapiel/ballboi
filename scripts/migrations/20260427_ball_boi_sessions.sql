CREATE TABLE IF NOT EXISTS ball_boi_sessions (
  id serial PRIMARY KEY,
  match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
  recorded_by_clerk_user_id text NOT NULL,
  status text NOT NULL DEFAULT 'recording',
  recording_started_at timestamptz NOT NULL DEFAULT now(),
  recording_stopped_at timestamptz,
  video_object_path text,
  video_content_type text,
  video_size_bytes integer,
  duration_seconds integer,
  processing_status text NOT NULL DEFAULT 'pending',
  processing_error text,
  ai_narrative text,
  metadata jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS match_shots (
  id serial PRIMARY KEY,
  session_id integer NOT NULL REFERENCES ball_boi_sessions(id) ON DELETE CASCADE,
  match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
  sequence_number integer NOT NULL,
  rally_number integer NOT NULL DEFAULT 1,
  player_id integer REFERENCES players(id) ON DELETE SET NULL,
  timestamp_seconds real NOT NULL,
  shot_type text NOT NULL,
  shot_type_confidence real,
  outcome text,
  outcome_confidence real,
  court_zone_name text,
  court_zone_x real,
  court_zone_y real,
  contact_x real,
  contact_y real,
  speed_mph real,
  spin_type text,
  depth text,
  angle_degrees real,
  player_stance text,
  clip_start_seconds real,
  clip_end_seconds real,
  raw_ml_data jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS match_statistics (
  id serial PRIMARY KEY,
  session_id integer NOT NULL REFERENCES ball_boi_sessions(id) ON DELETE CASCADE,
  match_id integer NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
  total_shots integer NOT NULL DEFAULT 0,
  total_rallies integer NOT NULL DEFAULT 0,
  avg_rally_length real NOT NULL DEFAULT 0,
  avg_shot_speed_mph real NOT NULL DEFAULT 0,
  fastest_shot_mph real NOT NULL DEFAULT 0,
  winners integer NOT NULL DEFAULT 0,
  errors integer NOT NULL DEFAULT 0,
  serves integer NOT NULL DEFAULT 0,
  forehands integer NOT NULL DEFAULT 0,
  backhands integer NOT NULL DEFAULT 0,
  volleys integer NOT NULL DEFAULT 0,
  overheads integer NOT NULL DEFAULT 0,
  heatmap_data jsonb NOT NULL DEFAULT '[]',
  shot_type_breakdown jsonb NOT NULL DEFAULT '{}',
  outcome_breakdown jsonb NOT NULL DEFAULT '{}',
  player_comparisons jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
